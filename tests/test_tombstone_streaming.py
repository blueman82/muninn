"""Resource and snapshot guarantees for synthetic erasure journals."""

from __future__ import annotations

import json
import os
import sqlite3
import tempfile
import tracemalloc
import unittest
from pathlib import Path
from typing import BinaryIO
from unittest import mock

from muninn import platform_io, tombstone_intent


class TombstoneStreamingTests(unittest.TestCase):
    """Retain complete intent without retaining repeated journal records."""

    def setUp(self) -> None:
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.home = Path(temp.name)
        self.path = self.home / "tombstones.jsonl"
        self.conn = sqlite3.connect(":memory:")
        self.addCleanup(self.conn.close)
        self.conn.execute(
            "CREATE TABLE tombstone(provider, level, session_root, thread_id,"
            " line, line_sha256, created_at)"
        )
        self.row: dict[str, object] = {
            "provider": "codex",
            "level": "session",
            "session_root": "synthetic-root",
            "created_at": 1,
        }

    def journal(self, data: bytes) -> None:
        """Write private generated bytes without accessing provider data."""
        self.path.write_bytes(data)
        self.path.chmod(0o600)

    def test_duplicate_history_does_not_retain_all_records(self) -> None:
        raw = json.dumps(self.row).encode() + b"\n"
        self.journal(raw * 10000)
        tracemalloc.start()
        try:
            intent = tombstone_intent.read_intent(self.conn, self.home)
            _, peak = tracemalloc.get_traced_memory()
        finally:
            tracemalloc.stop()
        self.assertEqual(len(intent.rows), 1)
        self.assertEqual(len(intent.missing), 1)
        # A small complete union must not retain a history of duplicate rows.
        self.assertLess(peak, 1024 * 1024)

    def test_large_valid_record_has_no_new_size_limit(self) -> None:
        identifier = "synthetic-" + "x" * (1024 * 1024)
        self.journal(
            json.dumps(self.row | {"session_root": identifier}).encode()
            + b"\n"
        )
        intent = tombstone_intent.read_intent(self.conn, self.home)
        self.assertEqual(intent.rows[0].session_root, identifier)
        self.assertEqual(intent.missing, intent.rows)

    def test_complete_union_preserves_table_and_first_journal_precedence(
        self,
    ) -> None:
        self.conn.executemany(
            "INSERT INTO tombstone VALUES ('codex','session',?,NULL,NULL,"
            "NULL,?)",
            [("synthetic-root", 9), ("table-only", 8)],
        )
        self.journal(
            b"".join(
                json.dumps(self.row | change).encode() + b"\r\n"
                for change in (
                    {},
                    {"session_root": "journal-only", "created_at": 3},
                    {"session_root": "journal-only", "created_at": 4},
                )
            )
        )
        intent = tombstone_intent.read_intent(self.conn, self.home)
        self.assertEqual(
            [(row.session_root, row.created_at) for row in intent.rows],
            [
                ("synthetic-root", 9.0),
                ("table-only", 8.0),
                ("journal-only", 3.0),
            ],
        )
        self.assertEqual(
            [row.session_root for row in intent.missing], ["journal-only"]
        )

    def test_late_malformed_duplicate_never_returns_partial_intent(
        self,
    ) -> None:
        raw = json.dumps(self.row).encode() + b"\n"
        before = list(self.conn.iterdump())
        for suffix in (b"{}\n", raw[:-1], b"\xff\n", b"\n"):
            with self.subTest(suffix=suffix):
                data = raw * 100 + suffix
                self.journal(data)
                with self.assertRaisesRegex(
                    ValueError, "^erasure_intent_invalid$"
                ):
                    tombstone_intent.read_intent(self.conn, self.home)
                self.assertEqual(list(self.conn.iterdump()), before)
                self.assertEqual(self.path.read_bytes(), data)

    def test_substitution_after_discovery_refuses_actual_replacement(
        self,
    ) -> None:
        self.journal(json.dumps(self.row).encode() + b"\n")
        replacement = self.home / "replacement"
        replacement.write_bytes(self.path.read_bytes())
        replacement.chmod(0o600)
        original = platform_io.open_regular

        def replace(
            path: Path,
            *,
            root: Path | None = None,
            expected: os.stat_result | None = None,
        ) -> BinaryIO:
            replacement.replace(path)
            return original(path, root=root, expected=expected)

        with (
            mock.patch.object(
                platform_io, "open_regular", side_effect=replace
            ),
            self.assertRaisesRegex(OSError, "source changed identity"),
        ):
            tombstone_intent.read_intent(self.conn, self.home)

    def test_cancellation_closes_journal_without_mutating_intent(self) -> None:
        raw = json.dumps(self.row).encode() + b"\n"
        self.journal(raw * 2)
        opened: list[BinaryIO] = []
        original = platform_io.open_regular

        def capture(
            path: Path,
            *,
            root: Path | None = None,
            expected: os.stat_result | None = None,
        ) -> BinaryIO:
            handle = original(path, root=root, expected=expected)
            opened.append(handle)
            return handle

        before = list(self.conn.iterdump())
        with (
            mock.patch.object(
                platform_io, "open_regular", side_effect=capture
            ),
            mock.patch.object(
                tombstone_intent,
                "canonical_record",
                side_effect=KeyboardInterrupt,
            ),
            self.assertRaises(KeyboardInterrupt),
        ):
            tombstone_intent.read_intent(self.conn, self.home)
        self.assertEqual(len(opened), 1)
        self.assertTrue(opened[0].closed)
        self.assertEqual(self.path.read_bytes(), raw * 2)
        self.assertEqual(list(self.conn.iterdump()), before)

    def test_consumer_cancellation_closes_suspended_journal(self) -> None:
        self.journal(json.dumps(self.row).encode() + b"\n")
        handle = platform_io.open_regular(self.path, root=self.home)
        self.addCleanup(handle.close)
        with (
            mock.patch.object(
                platform_io, "open_regular", return_value=handle
            ),
            mock.patch.object(
                tombstone_intent.IntentRow,
                "key",
                new_callable=mock.PropertyMock,
                side_effect=KeyboardInterrupt,
            ),
            self.assertRaises(KeyboardInterrupt),
        ):
            tombstone_intent.read_intent(self.conn, self.home)
        self.assertTrue(handle.closed)
        self.assertEqual(
            self.conn.execute("SELECT count(*) FROM tombstone").fetchone()[0],
            0,
        )
